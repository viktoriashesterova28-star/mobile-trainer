//     app        — общее название сервиса (не компания)
//     tint       — цветовая тема экрана (violet/blue/teal/amber/indigo/green/rose)
//     icon       — эмодзи
//     header     — { title, subtitle? }
//     popup      — { title, text } — попап при нажатии на кнопку
//     blocks     — массив блоков { t, ... } (text/offer/compare/cta и др.)
//     stories    — для формата story: массив строк (кейсы «три сторис»)
//   context   — условия задания: факты для редактора
//   question  — вопрос к участнику
//   options   — варианты { text, isCorrect } (isCorrect ровно у одного)
